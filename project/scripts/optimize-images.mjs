import sharp from 'sharp';
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'public/optimized/responsive');
await mkdir(output, { recursive: true });
const sources = (await readdir(path.join(root, 'public/optimized')))
  .filter(name => name.endsWith('.jpg'))
  .map(name => ({ source: `/optimized/${name}`, name: name.replace('.jpg', '') }));
sources.push({ source: '/ChatGPT Image Jun 9, 2025, 12_57_49 PM.png', name: 'logo' });
const images = {};
for (const { source, name } of sources) {
  const input = path.join(root, 'public', source);
  const metadata = await sharp(input).metadata();
  const widths = name === 'logo' ? [160, 320, 480] : [320, 640, 960, Math.min(1280, metadata.width)];
  const candidates = [];
  for (const width of [...new Set(widths.filter(w => w <= metadata.width))]) {
    const filename = `${name}-${width}.webp`;
    await sharp(input).rotate().resize({ width, withoutEnlargement: true })
      .webp({ quality: name === 'logo' ? 90 : 80, effort: 6 }).toFile(path.join(output, filename));
    candidates.push(`/optimized/responsive/${filename} ${width}w`);
  }
  images[source] = {
    src: candidates.at(-1).split(' ')[0], srcSet: candidates.join(', '),
    width: metadata.width, height: metadata.height,
  };
}
await writeFile(path.join(root, 'src/config/images.ts'),
  '// Generated by npm run images. Original assets are preserved.\n' +
  `export const optimizedImages: Record<string, { src: string; srcSet: string; width: number; height: number }> = ${JSON.stringify(images, null, 2)};\n`);
console.log(`Generated responsive WebP variants for ${sources.length} images.`);
